-- Полная схема для чистой базы. На уже развёрнутой базе не запускается:
-- там достаточно sql/001_alter.sql (его применяет scripts/bootstrap_db.py).

create schema if not exists gen_internal;

-- справочники
create table dim_category (
    category_id integer primary key,
    parent_id integer references dim_category (category_id),
    category_lvl integer not null check (category_lvl in (1, 2, 3)),
    category_name varchar(255) not null
);

create table dim_supplier (
    supplier_id integer primary key,
    contractor_name varchar(255) not null,
    plan_income_day_cnt integer not null check (plan_income_day_cnt between 7 and 28)
);

create table dim_customer (
    customer_id integer primary key,
    customer_type varchar(100) not null,
    customer_name varchar(255) not null,
    profile_type varchar(100)
);

create table dim_products (
    sku_id integer primary key,
    category_id integer not null references dim_category (category_id),
    supplier_id integer not null references dim_supplier (supplier_id),
    brand_name varchar(100) not null,
    price_segment integer not null check (price_segment in (1, 2, 3)),
    pack_size integer not null default 1,
    price_inc numeric(12, 2) not null check (price_inc > 0),
    price numeric(12, 2) not null,
    check (price >= price_inc)
);

create table dim_product_crosses (
    cross_group_id integer not null,
    sku_id integer not null references dim_products (sku_id),
    primary key (cross_group_id, sku_id)
);

create table current_assortment (
    sku_id integer not null references dim_products (sku_id),
    status varchar(50) not null check (status in ('активный', 'вывод', 'ввод')),
    date_from_dt date not null,
    date_to_dt date,
    primary key (sku_id, date_from_dt)
);

create table supplier_schedule (
    supplier_id integer not null references dim_supplier (supplier_id),
    order_dt date not null,
    plan_income_day_cnt integer not null,
    primary key (supplier_id, order_dt)
);

-- факты, которые пишет генератор
create table sale_order (
    sale_order_id bigint generated by default as identity primary key,
    customer_id integer not null references dim_customer (customer_id),
    order_dt date not null,
    status integer not null check (status in (0, 1))
);

create table sale_order_day (
    date_dt date not null,
    customer_id integer not null,
    sku_id integer not null references dim_products (sku_id),
    qnty integer not null check (qnty <> 0),
    price_sum numeric(12, 2) not null,
    price_inc_sum numeric(12, 2) not null,
    discount numeric(5, 2) not null default 0,
    primary key (date_dt, customer_id, sku_id)
);

create table income_order_day (
    order_line_id bigint generated by default as identity primary key,
    date_dt date not null,
    supplier_id integer not null references dim_supplier (supplier_id),
    sku_id integer not null references dim_products (sku_id),
    qnty integer not null check (qnty > 0)
);

create table income_day (
    income_line_id bigint generated by default as identity primary key,
    supplier_id integer not null references dim_supplier (supplier_id),
    date_dt date not null,
    sku_id integer not null references dim_products (sku_id),
    order_qnty integer not null check (order_qnty >= 0),
    income_qnty integer not null check (income_qnty >= 0),
    price_inc numeric(12, 2) not null check (price_inc > 0),
    income_order_dt date not null,
    income_day_cnt integer,
    is_new boolean not null default false
);

create table rest_day (
    date_dt date not null,
    sku_id integer not null references dim_products (sku_id),
    rest_qnty integer not null check (rest_qnty >= 0),
    rest_transit_qnty integer not null check (rest_transit_qnty >= 0),
    primary key (date_dt, sku_id)
);

-- скрытое состояние генератора
create table gen_internal.params (
    key text primary key,
    value text not null
);

create table gen_internal.sku_profile (
    sku_id integer primary key,
    root_category_id integer not null,
    demand_class text not null,
    base_daily numeric not null,
    drift_rate numeric not null,
    lifecycle text not null,
    shock_prob numeric not null,
    promo_elasticity numeric not null,
    abc_class text not null
);

create table gen_internal.customer_profile (
    customer_id integer primary key,
    customer_type text not null,
    profile_type text not null,
    order_interval_days numeric not null,
    order_size numeric not null,
    size_jitter numeric not null,
    activity_from date not null,
    activity_to date
);

create table gen_internal.sku_customer (
    sku_id integer not null,
    customer_id integer not null,
    weight numeric not null,
    primary key (sku_id, customer_id)
);

create table gen_internal.supplier_profile (
    supplier_id integer primary key,
    stable boolean not null,
    lead_sigma numeric not null,
    lead_bias numeric not null,
    short_prob numeric not null
);

create table gen_internal.cross_share (
    sku_id integer primary key,
    cross_group_id integer not null,
    base_share numeric not null
);

create table gen_internal.year_anomaly (
    year integer primary key,
    shift_months integer not null,
    winter_factor numeric not null
);

create table gen_internal.truth_demand (
    date_dt date not null,
    sku_id integer not null,
    demand_qnty integer not null,
    sold_qnty integer not null,
    lost_qnty integer not null,
    promo boolean not null,
    discount numeric not null,
    primary key (date_dt, sku_id)
);

create table gen_internal.calc_log (
    date_dt date primary key,
    sales_rows integer not null,
    order_rows integer not null,
    income_rows integer not null,
    oos_skus integer not null,
    calculated_at timestamp not null default now()
);

create table gen_internal.backorder (
    supplier_id integer not null,
    sku_id integer not null,
    order_dt date not null,
    order_qnty integer not null,
    open_qnty integer not null,
    resolve_dt date,
    primary key (supplier_id, sku_id, order_dt)
);
