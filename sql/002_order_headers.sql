-- Заказ и приход становятся документами: шапка и строки.
-- Ранее рассчитанные income_order_day и income_day удаляются, их нужно посчитать заново.
-- Идемпотентна, пока в базе ещё нет новой формы или миграция оборвалась посередине.

alter table dim_supplier add column if not exists order_day_of_week varchar(32);
alter table dim_supplier add column if not exists order_every_day_cnt integer;

do $$
begin
    if exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'supplier_schedule' and column_name = 'order_dt'
    ) then
        alter table supplier_schedule rename column order_dt to income_order_dt;
    end if;
end $$;

alter table supplier_schedule add column if not exists income_plan_dt date;

do $$
begin
    if exists (
        select 1 from information_schema.columns
        where table_schema = 'public'
          and table_name = 'supplier_schedule'
          and column_name = 'plan_income_day_cnt'
    ) then
        update supplier_schedule
        set income_plan_dt = income_order_dt + plan_income_day_cnt
        where income_plan_dt is null;
        alter table supplier_schedule drop column plan_income_day_cnt;
    end if;
end $$;

update dim_supplier s
set order_every_day_cnt = sub.gap
from (
    select supplier_id,
           ((max(income_order_dt) - min(income_order_dt)) / nullif(count(*) - 1, 0))::int as gap
    from supplier_schedule
    group by supplier_id
) sub
where s.supplier_id = sub.supplier_id
  and s.order_every_day_cnt is null
  and sub.gap is not null;

update dim_supplier
set order_every_day_cnt = plan_income_day_cnt
where order_every_day_cnt is null;

update dim_supplier s
set order_day_of_week = sub.days
from (
    select supplier_id, string_agg(dow::text, ',' order by dow) as days
    from (
        select distinct supplier_id, extract(isodow from income_order_dt)::int as dow
        from supplier_schedule
    ) d
    group by supplier_id
) sub
where s.supplier_id = sub.supplier_id
  and (s.order_day_of_week is null or s.order_day_of_week = '');

update dim_supplier
set order_day_of_week = '1,2,3,4,5,6,7'
where order_day_of_week is null or order_day_of_week = '';

update supplier_schedule s
set income_plan_dt = s.income_order_dt + d.plan_income_day_cnt
from dim_supplier d
where d.supplier_id = s.supplier_id
  and s.income_plan_dt is null;

alter table dim_supplier alter column order_day_of_week set not null;
alter table dim_supplier alter column order_every_day_cnt set not null;
alter table supplier_schedule alter column income_plan_dt set not null;

do $$
begin
    if not exists (
        select 1 from pg_constraint where conname = 'dim_supplier_order_every_day_cnt_check'
    ) then
        alter table dim_supplier
            add constraint dim_supplier_order_every_day_cnt_check check (order_every_day_cnt > 0);
    end if;
    if not exists (
        select 1 from pg_constraint where conname = 'supplier_schedule_plan_after_order'
    ) then
        alter table supplier_schedule
            add constraint supplier_schedule_plan_after_order check (income_plan_dt >= income_order_dt);
    end if;
end $$;

do $$
begin
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'public'
          and table_name = 'supplier_schedule'
          and column_name = 'supplier_schedule_id'
    ) then
        alter table supplier_schedule drop constraint supplier_schedule_pkey;
        alter table supplier_schedule
            add column supplier_schedule_id bigint generated by default as identity;
        alter table supplier_schedule
            add constraint supplier_schedule_pkey primary key (supplier_schedule_id);
        alter table supplier_schedule
            add constraint supplier_schedule_supplier_day_uq unique (supplier_id, income_order_dt);
    end if;
end $$;

create table if not exists income_order (
    income_order_id bigint generated by default as identity primary key,
    date_dt date not null,
    supplier_id integer not null references dim_supplier (supplier_id),
    unique (supplier_id, date_dt)
);

create table if not exists income_order_detail (
    income_order_detail_id bigint generated by default as identity primary key,
    income_order_id bigint not null references income_order (income_order_id) on delete cascade,
    sku_id integer not null references dim_products (sku_id),
    qnty integer not null check (qnty > 0),
    unique (income_order_id, sku_id)
);

create table if not exists income (
    income_id bigint generated by default as identity primary key,
    supplier_id integer not null references dim_supplier (supplier_id),
    date_dt date not null,
    income_day_cnt integer,
    income_order_id bigint not null unique references income_order (income_order_id) on delete cascade,
    income_order_dt date not null
);

create table if not exists income_detail (
    income_detail_id bigint generated by default as identity primary key,
    income_id bigint not null references income (income_id) on delete cascade,
    sku_id integer not null references dim_products (sku_id),
    order_qnty integer not null check (order_qnty > 0),
    income_qnty integer not null check (income_qnty >= 0),
    price_inc numeric(12, 2) not null check (price_inc > 0),
    is_new boolean not null default false,
    unique (income_id, sku_id),
    check (income_qnty <= order_qnty)
);

do $$
begin
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'gen_internal'
          and table_name = 'backorder'
          and column_name = 'income_order_id'
    ) then
        drop table if exists gen_internal.backorder;
        create table gen_internal.backorder (
            income_order_id bigint not null references income_order (income_order_id) on delete cascade,
            supplier_id integer not null,
            sku_id integer not null,
            order_dt date not null,
            order_qnty integer not null,
            open_qnty integer not null,
            resolve_dt date not null,
            primary key (income_order_id, sku_id)
        );
    end if;
end $$;

drop table if exists income_day;
drop table if exists income_order_day;
